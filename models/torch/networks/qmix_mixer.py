import torch
import torch.nn as nn
import torch.nn.functional as F
import numpy as np


class QMixer(nn.Module):
    """
    QMIX Mixing Network.
    
    Based on the PyMARL implementation (https://github.com/oxwhirl/pymarl).
    Uses hypernetworks conditioned on the global state to generate mixing weights,
    ensuring monotonicity (non-negative weights) for the Individual-Global-Max (IGM) property.
    
    Architecture:
        agent_qs (n_agents) → [W1 (abs)] → ELU → [W_final (abs)] + V(s) → Q_tot (scalar)
        
    Where W1, b1, W_final are generated by hypernetworks conditioned on global state,
    and V(s) is a state-dependent bias replacing the final bias term.
    """
    
    def __init__(
        self,
        n_agents: int,
        state_dim: int,
        mixing_embed_dim: int = 32,
        hypernet_layers: int = 2,
        hypernet_embed: int = 64,
        init_scale: float = None,
    ):
        super(QMixer, self).__init__()
        
        self.n_agents = n_agents
        self.state_dim = state_dim
        self.embed_dim = mixing_embed_dim
        
        # Hypernetwork for first layer weights
        if hypernet_layers == 1:
            self.hyper_w_1 = nn.Linear(self.state_dim, self.embed_dim * self.n_agents)
            self.hyper_w_final = nn.Linear(self.state_dim, self.embed_dim)
        elif hypernet_layers == 2:
            self.hyper_w_1 = nn.Sequential(
                nn.Linear(self.state_dim, hypernet_embed),
                nn.ReLU(),
                nn.Linear(hypernet_embed, self.embed_dim * self.n_agents)
            )
            self.hyper_w_final = nn.Sequential(
                nn.Linear(self.state_dim, hypernet_embed),
                nn.ReLU(),
                nn.Linear(hypernet_embed, self.embed_dim)
            )
        else:
            raise ValueError(f"hypernet_layers must be 1 or 2, got {hypernet_layers}")
        
        # State-dependent bias for hidden layer
        self.hyper_b_1 = nn.Linear(self.state_dim, self.embed_dim)
        
        # V(s) instead of a bias for the last layer
        self.V = nn.Sequential(
            nn.Linear(self.state_dim, self.embed_dim),
            nn.ReLU(),
            nn.Linear(self.embed_dim, 1)
        )

        if init_scale is not None:
            self._init_weights(float(init_scale))

    def _init_weights(self, init_scale: float):
        for module in self.modules():
            if isinstance(module, nn.Linear):
                nn.init.orthogonal_(module.weight, gain=init_scale)
                if module.bias is not None:
                    nn.init.zeros_(module.bias)
    
    def forward(self, agent_qs: torch.Tensor, states: torch.Tensor) -> torch.Tensor:
        """
        Forward pass of the mixing network.
        
        Args:
            agent_qs: Individual agent Q-values, shape [B, T, n_agents] or [B, n_agents]
            states: Global state, shape [B, T, state_dim] or [B, state_dim]
            
        Returns:
            Q_tot: Total Q-value, shape [B, T, 1] or [B, 1]
        """
        # Handle both [B, T, ...] and [B, ...] inputs
        has_time = agent_qs.dim() == 3
        if has_time:
            B, T, N = agent_qs.shape
            agent_qs = agent_qs.reshape(B * T, 1, N)
            states = states.reshape(B * T, -1)
        else:
            B = agent_qs.size(0)
            agent_qs = agent_qs.view(B, 1, self.n_agents)
            states = states.reshape(B, -1)
        
        # First layer
        w1 = torch.abs(self.hyper_w_1(states))
        b1 = self.hyper_b_1(states)
        w1 = w1.view(-1, self.n_agents, self.embed_dim)
        b1 = b1.view(-1, 1, self.embed_dim)
        hidden = F.elu(torch.bmm(agent_qs, w1) + b1)
        
        # Second layer
        w_final = torch.abs(self.hyper_w_final(states))
        w_final = w_final.view(-1, self.embed_dim, 1)
        
        # State-dependent bias
        v = self.V(states).view(-1, 1, 1)
        
        # Compute final output
        y = torch.bmm(hidden, w_final) + v
        
        # Reshape
        if has_time:
            q_tot = y.view(B, T, 1)
        else:
            q_tot = y.view(B, 1)
        
        return q_tot
